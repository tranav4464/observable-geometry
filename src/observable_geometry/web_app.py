"""Local browser interface for the existing model-only distinguish command."""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np
import pandas as pd
import streamlit as st

from observable_geometry.cli import run_distinguish
from observable_geometry.web_results import verify_completed_run


st.set_page_config(page_title="Observable Geometry", layout="wide")
st.title("Observable Geometry")
st.caption("Inspect predicted scalp-pattern similarity under your declared EEG model.")
st.info("Scores describe a forward model, not measured neural activity, localization accuracy, or a probability.")

mode = st.radio("What would you like to do?", ["Inspect an existing run", "Run a model"], horizontal=True)
if mode == "Run a model":
    st.write("Use local files on this computer. The model bundle must contain only the allowed forward-model arrays; do not include recorded EEG samples.")
    bundle = st.text_input("Model-only NPZ bundle (absolute path)")
    metadata = st.text_input("Matching metadata JSON (absolute path)")
    output = st.text_input("New output directory (absolute path)")
    c1, c2 = st.columns(2)
    minimum_distance = c1.number_input("Minimum straight-line distance (mm)", min_value=0.0, value=20.0)
    top_k = c2.number_input("Alternatives per source", min_value=1, max_value=100, value=5)
    if st.button("Run diagnostic", type="primary"):
        if not bundle or not metadata or not output:
            st.error("Enter all three paths.")
        else:
            try:
                args = argparse.Namespace(bundle=Path(bundle), metadata=Path(metadata), output=Path(output),
                                          minimum_distance_mm=float(minimum_distance), top_k=int(top_k), block_size=128)
                with st.spinner("Comparing model source patterns…"):
                    run_distinguish(args)
                st.session_state["result_directory"] = str(Path(output).resolve())
                st.success("Run complete. The result below was generated by the same diagnostic as the CLI.")
            except (ValueError, OSError, KeyError, TypeError) as exc:
                st.error(f"Run failed: {exc}")
else:
    existing = st.text_input("Completed run directory (absolute path)", value=st.session_state.get("result_directory", ""))
    if existing:
        st.session_state["result_directory"] = existing

result_dir = Path(st.session_state.get("result_directory", "")) if st.session_state.get("result_directory") else None
if result_dir is not None:
    summary_path = result_dir / "summary.json"
    pairs_path = result_dir / "ranked_pairs.csv"
    if not summary_path.is_file() or not pairs_path.is_file():
        st.warning("This directory does not contain a completed distinguish run.")
    else:
        try:
            summary = verify_completed_run(result_dir)
            pairs = pd.read_csv(pairs_path)
            required = {"source_index", "source_id", "rank", "candidate_index", "candidate_id",
                        "distance_mm", "absolute_cosine", "profiled_residual_unit_snr"}
            if not required.issubset(pairs.columns):
                raise ValueError("The ranked-pairs file has an unexpected schema")
            st.subheader("Run summary")
            st.caption("Local output files match this run's SHA-256 manifest. This checks file integrity, not scientific validity or the identity of the person who created the manifest.")
            a, b, c = st.columns(3)
            a.metric("Candidate sources", f"{summary['source_count']:,}")
            b.metric("Exported ranked rows", f"{len(pairs):,}")
            c.metric("Median best eligible similarity", f"{summary['median_best_distant_abs_cosine']:.3f}")
            st.caption(f"Minimum separation: {summary['minimum_euclidean_separation_mm']} mm · "
                       f"covariance rank: {summary['covariance_rank']} · "
                       f"dataset: {summary.get('metadata', {}).get('dataset', 'unspecified')}")

            first = pairs.loc[pairs["rank"] == 1]
            st.subheader("Best eligible alternative per source")
            counts, edges = np.histogram(first["absolute_cosine"].to_numpy(), bins=np.linspace(0, 1, 31))
            st.bar_chart(pd.DataFrame({"Source count": counts}, index=np.round((edges[:-1] + edges[1:]) / 2, 2)))
            st.caption("This is a distribution of modeled source vertices, not independent neural events. A high score has no validated decision cutoff.")

            st.subheader("Explore one source")
            selected = st.selectbox("Source index", first["source_index"].tolist())
            subset = pairs.loc[pairs["source_index"] == selected].sort_values("rank")
            st.dataframe(subset, hide_index=True, width="stretch")
            st.scatter_chart(subset, x="distance_mm", y="absolute_cosine", x_label="Straight-line distance (mm)", y_label="Absolute cosine")
            st.caption("The residual is the difference between unit whitened patterns after fitting the alternative's scale and sign. It is not volts or a localization error.")
            st.download_button("Download ranked CSV", pairs_path.read_bytes(), file_name="ranked_pairs.csv", mime="text/csv")
            with st.expander("Provenance and limits"):
                st.json({"inputs": summary.get("inputs"), "parameters": summary.get("parameters"),
                         "claim_boundary": summary.get("claim_boundary")})
                st.write("Check run_manifest.json and npz_key_access.jsonl in the same directory for code and input hashes and array access.")
        except (ValueError, KeyError, OSError, json.JSONDecodeError, pd.errors.ParserError) as exc:
            st.error(f"Could not read this run: {exc}")
